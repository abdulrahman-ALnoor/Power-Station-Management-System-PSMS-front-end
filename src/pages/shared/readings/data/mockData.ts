export const getMeterReadingStats = (readings: MeterReading[]): MeterReadingStatsData => {
 return {
 totalReadings: readings.length,
 approvedReadings: readings.filter(r => r.status === 'approved').length,
 pendingReadings: readings.filter(r => r.status === 'pending').length,
 rejectedReadings: readings.filter(r => r.status === 'rejected').length,
 totalConsumption: readings.reduce((sum, r) => sum + r.consumption, 0),
 totalReadingCost: readings.reduce((sum, r) => sum + r.reading_cost, 0),
 }
}
